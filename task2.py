import re


date_patterns = [
    # Относительные даты
    r'\b(?:сегодня|вчера|позавчера|завтра|послезавтра|этим утром|сегодня утром|сегодня вечером|вчера вечером)\b',

    # Относительные периоды: на прошлой неделе
    r'\b(?:на\s+)?(?:прошлой|прошедшей|следующей|будущей|этой|предыдущей)\s+(?:неделе|неделю|месяце|месяц|году|год)\b',

    # Периоды, заканчивающиеся словом "назад"
    r'\b(?:один|одна|две|два|три|четыре|пять|шесть|семь|восемь|девять|десять|\d+)\s+(?:день|дня|дней|неделю|недели|недель|месяц|месяца|месяцев|год|года|лет)\s+назад\b',

    # День недели с числом, месяцем и годом
    r'\b(?:(?:в|во)\s+)?(?:(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье),?\s+)?\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)(?:\s+\d{4}\s+года)?\b',

    # Первое или второе полугодие
    r'\b(?:(?:с|по|в|до)\s+)?(?:первое|второе)\s+полугодие\s+\d{4}\s+года\b',

    # Месяц и год
    r'\b(?:(?:с|по|в|до|из)\s+)?(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря|январе|феврале|марте|апреле|мае|июне|июле|августе|сентябре|октябре|ноябре|декабре)\s+\d{4}\s+года\b',

    # Диапазон лет
    r'\bс\s+\d{4}\s+по\s+\d{4}\s+годы\b',

    # Год
    r'\b(?:(?:в|с|по|до|из)\s+)?\d{4}\s+года\b',

    # Месяц без года
    r'\b(?:в|во|с|по|до|из)\s+(?:январе|феврале|марте|апреле|мае|июне|июле|августе|сентябре|октябре|ноябре|декабре|января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)\b',

    # День недели без числа
    r'\b(?:в|во)\s+(?:понедельник|понедельника|вторник|вторника|среду|среде|четверг|четверга|пятницу|пятнице|субботу|субботе|воскресенье)\b'
]


# Ввод текста
print("Введите текст. Для завершения оставьте строку пустой:")

text = ""

while True:
    line = input()
    if not line:
        break
    text += line + "\n"


# Поиск дат по всем регулярным выражениям
date_matches = []

for pattern in date_patterns:
    date_matches.extend(re.finditer(pattern, text, re.IGNORECASE))


# Сортировка совпадений по позиции и длине
date_matches.sort(key=lambda match: (match.start(), -len(match.group())))

# Удаление вложенных и повторяющихся совпадений
unique_dates = []

for match in date_matches:
    if not unique_dates or match.start() >= unique_dates[-1].end():
        unique_dates.append(match)



# Вывод дат
print("\n--- УПОМИНАНИЯ ДАТ ---")

if unique_dates:
    for match in unique_dates:
        print(match.group())
else:
    print("Упоминания дат не найдены.")


# Статистика
print("\n--- СТАТИСТИКА ---")
print("Количество упоминаний дат:", len(unique_dates))
